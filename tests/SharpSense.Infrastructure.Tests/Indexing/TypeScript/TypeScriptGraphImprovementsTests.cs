    [Fact]
    public async Task WhenTypeScriptFilesAreGenerated_ThenSkipsGeneratedFilesWhileIndexingHandwrittenImporters()
    {
        var fileSystem = CreateRepositoryFileSystem(
            (Absolute("/repo/web/package.json"), """{ "name": "demo-web" }"""),
            (Absolute("/repo/web/tsconfig.json"), """{ "include": ["src"] }"""),
            (Absolute("/repo/web/src/generated/client.ts"),
                """
                /* eslint-disable */
                // Generated by Microsoft Kiota
                export interface GeneratedClient {
                    get(): void;
                }
                """),
            (Absolute("/repo/web/src/schema.generated.ts"),
                """
                export interface SchemaDto {
                    id: string;
                }
                """),
            (Absolute("/repo/web/src/banner.ts"),
                """
                export function warningText() {
                    return "do not edit this setting in production";
                }
                """),
            (Absolute("/repo/web/src/api.ts"),
                """
                import type { GeneratedClient } from "./generated/client";
                import type { SchemaDto } from "./schema.generated";
                import { warningText } from "./banner";

                export function loadApi(client: GeneratedClient): SchemaDto | string {
                    return warningText();
                }
                """));
        var extractor = CreateExtractor(fileSystem);

        var result = await extractor.Extract(
            new ExtractionContext(Absolute("/repo/web/tsconfig.json"), null),
            TestContext.Current.CancellationToken);

        result.IsSuccess.Should().BeTrue();
        result.Value.CodeNodes.Select(static node => node.CanonicalId).Should().BeEquivalentTo(
            [
                "code:ts:web/src/api.ts:loadApi",
                "code:ts:web/src/banner.ts:warningText"
            ]);
        result.Value.Edges.Should().Contain(edge =>
            edge.CallerId == "code:ts:web/src/api.ts:loadApi" &&
            edge.CalleeId == "code:ts:web/src/banner.ts:warningText" &&
            edge.EdgeType == EdgeType.MethodCall);
    }

    [Fact]
    public async Task WhenTypeScriptProjectHasPackageJsonOrTsConfig_ThenEmitsDeterministicProjectNodesAndParentEdges()
    {
        var fileSystem = CreateRepositoryFileSystem(
            (Absolute("/repo/apps/ui/package.json"), """{ "name": "sharpsense-ui" }"""),
            (Absolute("/repo/apps/ui/tsconfig.json"), """{ "include": ["src"] }"""),
            (Absolute("/repo/apps/ui/src/Scene.ts"),
                """
                export class Scene {
                    render() {
                        return 1;
                    }
                }
                """),
            (Absolute("/repo/packages/shared/tsconfig.json"), """{ "include": ["src"] }"""),
            (Absolute("/repo/packages/shared/src/math.ts"),
                """
                export function add(left: number, right: number) {
                    return left + right;
                }
                """));
        var extractor = CreateExtractor(fileSystem);

        var uiResult = await extractor.Extract(
            new ExtractionContext(Absolute("/repo/apps/ui/tsconfig.json"), null),
            TestContext.Current.CancellationToken);
        var sharedResult = await extractor.Extract(
            new ExtractionContext(Absolute("/repo/packages/shared/tsconfig.json"), null),
            TestContext.Current.CancellationToken);

        uiResult.Value.Projects.Should().ContainSingle(project =>
            project.Id == "project:ts:apps/ui/package.json" &&
            project.Name == "sharpsense-ui" &&
            project.RelativeFilePath == "apps/ui/package.json");
        uiResult.Value.CodeNodes.Should().OnlyContain(node => node.ProjectId == "project:ts:apps/ui/package.json");
        uiResult.Value.Edges.Should().Contain(edge =>
            edge.CallerId == "project:ts:apps/ui/package.json" &&
            edge.CalleeId == "code:ts:apps/ui/src/Scene.ts:Scene" &&
            edge.EdgeType == EdgeType.ParentOf);
        uiResult.Value.Edges.Should().NotContain(edge =>
            edge.CallerId == "project:ts:apps/ui/package.json" &&
            edge.CalleeId == "code:ts:apps/ui/src/Scene.ts:Scene.render" &&
            edge.EdgeType == EdgeType.ParentOf);

        sharedResult.Value.Projects.Should().ContainSingle(project =>
            project.Id == "project:ts:packages/shared/tsconfig.json" &&
            project.Name == "shared" &&
            project.RelativeFilePath == "packages/shared/tsconfig.json");
    }

