            edge.CallerId == "code:ts:web/src/Scene.ts:Scene.theme" &&
            edge.CalleeId == "code:ts:web/src/buffers.ts:pickNode");
    }

    [Fact]
    public async Task WhenExtractingTypeScriptCallsJsxInstantiationsAndHeritage_ThenEmitsSymbolLevelEdges()
    {
        var fileSystem = CreateRepositoryFileSystem(
            (Absolute("/repo/web/package.json"), """{ "name": "sharpsense-ui" }"""),
            (Absolute("/repo/web/tsconfig.json"), """{ "include": ["src"] }"""),
            (Absolute("/repo/web/src/contracts.ts"),
                """
                export interface IRenderer {
                    render(): void;
                }

                export class BaseScene {}
                """),
            (Absolute("/repo/web/src/buffers.ts"),
                """
                export class BufferStore {
                    find(x: number) {
                        return x;
                    }
                }

                export function pickGraphNode(x: number) {
                    return x;
                }
                """),
            (Absolute("/repo/web/src/GraphScene.ts"),
                """
                import { BaseScene, type IRenderer } from "./contracts";
                import { BufferStore, pickGraphNode } from "./buffers";

                export class GraphScene extends BaseScene implements IRenderer {
                    private store: BufferStore = new BufferStore();

                    render() {
                        return this.pick(1);
                    }

                    pick(clientX: number) {
                        this.store.find(clientX);
                        return pickGraphNode(clientX);
                    }
                }
                """),
            (Absolute("/repo/web/src/GraphCanvas.tsx"),
                """
                import { useRef } from "react";
                import { GraphScene } from "./GraphScene";

                export function GraphCanvas({ onSelect }: { onSelect: (id: number) => void }) {
                    const sceneRef = useRef<GraphScene | null>(null);
                    const created = new GraphScene();
                    sceneRef.current?.pick(10);
                    created.render();
                    return <canvas onClick={() => onSelect(1)} />;
                }
                """),
            (Absolute("/repo/web/src/ExplorerPage.tsx"),
                """
                import { GraphCanvas } from "./GraphCanvas";

                export function ExplorerPage() {
                    return <GraphCanvas onSelect={() => {}} />;
                }
                """));
        var extractor = CreateExtractor(fileSystem);

        var result = await extractor.Extract(
            new ExtractionContext(Absolute("/repo/web/tsconfig.json"), null),
            TestContext.Current.CancellationToken);

        result.IsSuccess.Should().BeTrue();
        result.Value.Edges.Should().Contain(edge =>
            edge.CallerId == "code:ts:web/src/GraphScene.ts:GraphScene" &&
            edge.CalleeId == "code:ts:web/src/contracts.ts:BaseScene" &&
            edge.EdgeType == EdgeType.Implements);
        result.Value.Edges.Should().Contain(edge =>
            edge.CallerId == "code:ts:web/src/GraphScene.ts:GraphScene" &&
            edge.CalleeId == "code:ts:web/src/contracts.ts:IRenderer" &&
            edge.EdgeType == EdgeType.Implements);
        result.Value.Edges.Should().Contain(edge =>
            edge.CallerId == "code:ts:web/src/GraphScene.ts:GraphScene.render" &&
            edge.CalleeId == "code:ts:web/src/GraphScene.ts:GraphScene.pick" &&
            edge.EdgeType == EdgeType.MethodCall);
        result.Value.Edges.Should().Contain(edge =>
            edge.CallerId == "code:ts:web/src/GraphScene.ts:GraphScene.pick" &&
            edge.CalleeId == "code:ts:web/src/buffers.ts:BufferStore.find" &&
            edge.EdgeType == EdgeType.MethodCall);
        result.Value.Edges.Should().Contain(edge =>
            edge.CallerId == "code:ts:web/src/GraphScene.ts:GraphScene.pick" &&
            edge.CalleeId == "code:ts:web/src/buffers.ts:pickGraphNode" &&
            edge.EdgeType == EdgeType.MethodCall);
        result.Value.Edges.Should().Contain(edge =>
            edge.CallerId == "code:ts:web/src/GraphCanvas.tsx:GraphCanvas" &&
            edge.CalleeId == "code:ts:web/src/GraphScene.ts:GraphScene" &&
            edge.EdgeType == EdgeType.Instantiates);
        result.Value.Edges.Should().Contain(edge =>
            edge.CallerId == "code:ts:web/src/GraphCanvas.tsx:GraphCanvas" &&
            edge.CalleeId == "code:ts:web/src/GraphScene.ts:GraphScene.pick" &&
            edge.EdgeType == EdgeType.MethodCall);
        result.Value.Edges.Should().Contain(edge =>
            edge.CallerId == "code:ts:web/src/GraphCanvas.tsx:GraphCanvas" &&
            edge.CalleeId == "code:ts:web/src/GraphScene.ts:GraphScene.render" &&
            edge.EdgeType == EdgeType.MethodCall);
        result.Value.Edges.Should().Contain(edge =>
            edge.CallerId == "code:ts:web/src/ExplorerPage.tsx:ExplorerPage" &&
            edge.CalleeId == "code:ts:web/src/GraphCanvas.tsx:GraphCanvas" &&
            edge.EdgeType == EdgeType.MethodCall);
    }

