    private static TypeScriptLanguageExtractor CreateExtractor(MockFileSystem fileSystem)
    {
        var workspace = new RepositoryWorkspace(Absolute("/repo"), Absolute("/test-storage/index.db"), fileSystem);
        var tsConfigResolver = new TsConfigResolver(workspace, fileSystem);
        var sourceDiscoverer = new TypeScriptSourceDiscoverer(
            workspace,
            new WorkspaceFileDiscoverer(workspace, fileSystem),
            fileSystem,
            tsConfigResolver);
        var projectResolver = new TypeScriptProjectResolver(workspace, fileSystem);

        return new TypeScriptLanguageExtractor(
            sourceDiscoverer,
            fileSystem,
            [
                new CodeNodeExtractionPass(),
                new ImportDependencyPass(tsConfigResolver, workspace),
                new TypeScriptSymbolReferencePass(),
                new HttpEdgeExtractionPass()
            ],
            projectResolver);
    }

    private static MockFileSystem CreateRepositoryFileSystem(params (string Path, string Content)[] files)
    {
        var data = new Dictionary<string, MockFileData>
        {
            [Absolute("/repo/.git/HEAD")] = new("ref: refs/heads/main")
        };
        foreach (var (path, content) in files)
        {
            data[path] = new(content);
        }

        return new MockFileSystem(data, Absolute("/repo"));
    }
